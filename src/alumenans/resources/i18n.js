let UI_LANG = (() => {
  const asked = new URLSearchParams(location.search).get("lang");
  return Object.prototype.hasOwnProperty.call(I18N, asked) ? asked : "ru";
})();

function UI_LOCALE(){
  return UI_LANG === "ru" ? "ru-RU" : "en-GB";
}

function tr(key, params){
  let text = I18N[UI_LANG][key];
  if (text === undefined) text = I18N.ru[key];
  if (text === undefined) return key;
  if (params){
    text = text.replace(/\{(\w+)\}/g, (whole, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole);
  }
  return text;
}

const PLURAL_RULES = {};
function trn(key, n, params){
  const rules = PLURAL_RULES[UI_LANG] || (PLURAL_RULES[UI_LANG] = new Intl.PluralRules(UI_LOCALE()));
  let form = rules.select(Number(n) || 0);
  if (!["one", "few", "many"].includes(form)) form = "many";
  const table = I18N[UI_LANG];
  if (!(key + "." + form in table)) form = "many";
  return tr(key + "." + form, Object.assign({n}, params || {}));
}

/* Static markup carries keys instead of text: data-i18n for the text,
   data-i18n-title / -placeholder / -aria-label for attributes, and
   data-i18n-n for a counted text. */
function applyStaticText(root){
  (root || document).querySelectorAll("[data-i18n]").forEach(node => {
    node.textContent = node.dataset.i18nN
      ? trn(node.dataset.i18n, Number(node.dataset.i18nN))
      : tr(node.dataset.i18n);
  });
  for (const attribute of ["title", "placeholder", "aria-label"]){
    (root || document).querySelectorAll(`[data-i18n-${attribute}]`).forEach(node => {
      node.setAttribute(attribute, tr(node.getAttribute(`data-i18n-${attribute}`)));
    });
  }
  document.documentElement.lang = UI_LANG;
}
